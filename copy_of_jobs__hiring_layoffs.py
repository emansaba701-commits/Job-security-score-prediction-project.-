# ====================== 2. Target ko bins mein convert karo ======================
Clean_df['job_security_bin'] = pd.qcut(Clean_df['job_security_score'], q=4, labels=False)

# ====================== 3. Chi-Square Test ======================
alpha = 0.05
chi2_results = []

for col in cat_features:
    contingency = pd.crosstab(Clean_df[col], Clean_df['job_security_bin'])
    chi2_stat, p_val, dof, expected = chi2_contingency(contingency)

    decision = 'Reject Null (Keep Feature)' if p_val < alpha else 'Accept Null (Drop Feature)'

    chi2_results.append({
        'Feature': col,
        'Chi2_Statistic': round(chi2_stat, 4),
        'P_Value': round(p_val, 6),
        'Decision': decision
    })

# ====================== 4. Results ko DataFrame banao ======================
chi2_df = pd.DataFrame(chi2_results)

# Sorted by P-Value (important features pehle)
chi2_df = chi2_df.sort_values('P_Value').reset_index(drop=True)

# Display
